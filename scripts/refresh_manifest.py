#!/usr/bin/env python3
"""Regenerate SHA256SUMS after an intentionally reviewed repository change.

A self-signed checksum list is for integrity auditing, not authenticity.
Only run after reviewing source and documentation changes.
"""
from pathlib import Path
import hashlib
ROOT=Path(__file__).resolve().parents[1]
MANIFEST=ROOT/'checks'/'SHA256SUMS.txt'
EXCLUDE={MANIFEST.resolve()}
SKIP_DIRS={'.git','.pytest_cache','__pycache__','.venv','venv'}
SKIP_FILES={'numerical_tests.json'}
files=[]
for p in ROOT.rglob('*'):
    if not p.is_file() or any(part in SKIP_DIRS for part in p.relative_to(ROOT).parts):continue
    if p.name in SKIP_FILES or p.resolve() in EXCLUDE:continue
    files.append(p)
MANIFEST.parent.mkdir(parents=True,exist_ok=True)
with MANIFEST.open('w',encoding='utf8') as f:
    f.write('# SHA256 content manifest for curated Git snapshot; generated by scripts/refresh_manifest.py\n')
    for p in sorted(files):
        f.write(hashlib.sha256(p.read_bytes()).hexdigest()+'  '+p.relative_to(ROOT).as_posix()+'\n')
print('Hashed',len(files),'files ->',MANIFEST)
